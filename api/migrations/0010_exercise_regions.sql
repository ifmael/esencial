-- pertenece a una o varias regiones del mapa anatómico (`exercise_regions`),
-- más finas que el grupo de `exercise_tags`; toda región cuelga de un grupo que
-- el ejercicio ya tenía como tag, y el vocabulario (sin lado, sin anatomía de
-- relleno) es el de `src/muscle-regions.ts`, espejo de `web/src/components/body-map/`.
-- Aplica una sola vez (runner en _cf_D1_MIGRATIONS). Idempotente vía OR IGNORE.
